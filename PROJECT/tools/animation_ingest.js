#!/usr/bin/env node
// Generate the sample registry from indexed source frames. Never hand-edit the registry.
// node tools/animation_ingest.js [art-src/pvz-ai/animation/sample-frames.json]
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..'), SRC = path.join(ROOT, 'pvz-garden');
const input = process.argv[2] || path.join(ROOT, 'art-src/pvz-ai/animation/sample-frames.json');
const oi=process.argv.indexOf('--out'), filename=oi>0?process.argv[oi+1]:'art-v2-ai-sample.js';
if(!/^art-v2-ai-[a-z0-9-]+\.js$/.test(filename))throw Error('Invalid generated filename');
const records = JSON.parse(fs.readFileSync(input, 'utf8'));
const CH = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
const clips = {
  plant: [['idle',2,2,true],['walk',4,7,true],['attack',3,8,false],['hurt',1,1,false],['knockedOut',2,3,false],['cheer',2,4,true],['sleep',1,1,false]],
  zombie: [['idle',2,2,true],['walk',4,6,true],['attack',3,8,false],['hurt',1,1,false],['fall',3,5,false]],
  boss: [['idle',2,2,true],['attack',3,6,false],['hurt',1,1,false],['defeated',3,4,false]],
};
function rle(row) {
  let out=''; for(let i=0;i<row.length;){let j=i+1;while(j<row.length&&row[j]===row[i])j++;const n=j-i;out+=n>=3?n+row[i]:row[i].repeat(n);i=j;}return out;
}
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const sourceHashes=Object.fromEntries(records.map(r=>[r.source,hash(path.join(ROOT,r.source))]));
const lines=['// '+filename+' — GENERATED by tools/animation_ingest.js. Do not hand-edit.', '// Sources and recorded per-frame head anchors: '+path.relative(ROOT,path.resolve(input))+'.', '// Indexed input SHA-256: '+hash(input), '// Source image SHA-256: '+JSON.stringify(sourceHashes), '(function () {', "  'use strict';", '  const A = PX.v2ai.add;'];
let count=0;
for(const r of records){
  if(!clips[r.kind])throw Error('Unknown kind '+r.kind);
  const N=r.kind==='boss'?96:64;
  const want=clips[r.kind].reduce((n,c)=>n+c[1],0);
  if(r.frames.length!==want)throw Error(r.id+': want '+want+' frames');
  const encoded=r.frames.map(f=>{
    if(f.N!==N||f.rows.length!==N||f.rows.some(row=>row.length!==N))throw Error(r.id+': bad canvas');
    if(f.palette.length>52||f.palette.some(c=>!/^#[0-9a-f]{6}$/i.test(c)))throw Error(r.id+': invalid palette');
    if(!f.head||!['hx','hy','hr','ey','front'].every(k=>Number.isFinite(f.head[k])))throw Error(r.id+': missing anchors');
    if(f.rows.some(row=>[...row].some(c=>c!=='.'&&(CH.indexOf(c)<0||CH.indexOf(c)>=f.palette.length))))throw Error(r.id+': invalid pixel');
    return {pal:f.palette,rle:f.rows.map(rle),head:f.head};
  });
  const data={...encoded[0],clips:{}};let i=0;
  for(const [name,n,fps,loop] of clips[r.kind]){data.clips[name]={fps,loop,frames:encoded.slice(i,i+n)};i+=n;}
  lines.push('  A('+JSON.stringify(r.kind)+', '+JSON.stringify(r.id)+', '+JSON.stringify(r.stage??null)+', '+JSON.stringify(data)+');');
  count+=encoded.length;
}
lines.push('})();','');
const writeAtomic=(file,text)=>{const tmp=file+'.'+process.pid+'.tmp';fs.writeFileSync(tmp,text);fs.renameSync(tmp,file);};
writeAtomic(path.join(SRC,filename),lines.join('\n'));
const idx=path.join(SRC,'index.html');let html=fs.readFileSync(idx,'utf8');
if(!html.includes('src="'+filename+'"')){html=html.replace('<script src="data.js"></script>','<script src="'+filename+'"></script>\n<script src="data.js"></script>');writeAtomic(idx,html);}
console.log('Generated '+records.length+' character looks, '+count+' drawn frames.');
