#!/usr/bin/env node
// Integration checks for drawn clips, cache identity, geometry, and untouched fallbacks.
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert'),crypto=require('crypto');
const root=path.join(__dirname,'..'),src=path.join(root,'pvz-garden');
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const skipSourceImages=process.argv.includes('--skip-source-image-hashes');
if(skipSourceImages)console.log('Raw source-image hashes explicitly skipped; indexed JSON and runtime-frame checks remain enabled.');
for(const [,file] of fs.readFileSync(path.join(src,'index.html'),'utf8').matchAll(/src="(art-v2-ai-[a-z0-9-]+\.js)"/g)){
  const text=fs.readFileSync(path.join(src,file),'utf8');
  if(!text.includes('GENERATED by tools/animation_ingest.js'))continue;
  const input=text.match(/head anchors: (.+\.json)\./)?.[1],expected=text.match(/Indexed input SHA-256: ([a-f0-9]+)/)?.[1];
  assert(input&&expected,file+': missing provenance; regenerate the registry');
  assert.strictEqual(hash(path.join(root,input)),expected,file+': indexed source changed; regenerate the registry');
  const sources=JSON.parse(text.match(/Source image SHA-256: (.+)/)[1]);
  if(!skipSourceImages)for(const [source,expected]of Object.entries(sources))assert.strictEqual(hash(path.join(root,source)),expected,file+': source image changed: '+source);
}
const exporter=path.join(__dirname,'v2_export.js');
const bootstrap=fs.readFileSync(exporter,'utf8').split('// ---------- colours -> RGBA ----------')[0];
const env={require,__dirname,process:{argv:[]},console};
vm.runInNewContext(bootstrap+'\nthis.testPX=PX;this.testD=D;',env);
const PX=env.testPX, D=env.testD;
PX.useV2(true);
let count=0,looks=0;
for(const kind of ['plant','zombie','boss'])for(const [id,entry] of Object.entries(PX.v2ai.store[kind])){
  const stages=kind==='plant'?Object.entries(entry):[[null,entry]];
  for(const [stage,d] of stages){
    if(!d.clips)continue;looks++;
    const L=kind==='plant'?{species:id,stage:+stage}:kind==='zombie'?{zombie:id}:{boss:id};
    for(const [clip,spec]of Object.entries(d.clips))for(let i=0;i<spec.frames.length;i++){
      const P={animClip:clip,animFrame:i};
      const grid=PX.hires(()=>{
        if(kind==='plant')return PX.buildPlant(L,P);
        if(kind==='zombie')return PX.buildZombie(L,P);
        const g=new PX.Grid(48,48);PX.BOSS_ART2[id].draw(g,P);return g;
      });
      assert.deepStrictEqual(Array.from(grid.a),Array.from(PX.v2ai.decode(spec.frames[i]).a),id+' '+clip+'-'+i+': renderer altered drawn pixels');
      assert.strictEqual(PX.v2ai.geomOf(spec.frames[i]),spec.frames[i].head,'head metadata must be reused');
      const a=kind==='boss'?PX.critter(id,P):PX.sprig(L,P);
      const b=kind==='boss'?PX.critter(id,P):PX.sprig(L,P);
      assert.strictEqual(a,b,'identical frame should reuse its canvas');
      count++;
    }
    const attack=[0,.5,1].map(k=>PX.v2ai.pose(L,{clip:'attack'},0,k).animFrame);
    assert.deepStrictEqual(attack,[0,1,2],'one-shot progress must include windup, strike, recovery');
    const unique=new Set();
    for(let i=0;i<100;i++){
      const P=PX.v2ai.pose(L,{},i/20);
      unique.add(kind==='boss'?PX.critter(id,P):PX.sprig(L,P));
      assert(!('clipProgress'in P),'continuous progress leaked into cache key');
    }
    assert.strictEqual(unique.size,2,'breathing should cycle exactly two cached frames');
    PX.useV2(false);const old={walk:true,frame:1};assert.strictEqual(PX.v2ai.pose(L,old,4),old,'disabled v2 must preserve legacy pose');PX.useV2(true);
  }
}
const legacy={walk:true,frame:1,eyes:'happy'};
const still=Object.entries(PX.v2ai.store.plant).find(([,stages])=>stages[0]&&!stages[0].clips);
if(still)assert.strictEqual(PX.v2ai.pose({species:still[0],stage:0},legacy,3),legacy,'one-picture fallback changed');
else{
  // Keep compatibility coverage once the production queue converts every family.
  const sample={...Object.values(PX.v2ai.store.plant)[0][0]};delete sample.clips;
  PX.v2ai.store.plant.__legacy_still_test={0:sample};
  assert.strictEqual(PX.v2ai.pose({species:'__legacy_still_test',stage:0},legacy,3),legacy,'one-picture fallback changed');
  delete PX.v2ai.store.plant.__legacy_still_test;
}
const coded=Object.keys(D.PLANTS).find(id=>!PX.v2ai.store.plant[id]?.[0]);
assert.strictEqual(PX.v2ai.pose({species:coded||'__unregistered_family',stage:0},legacy,3),legacy,'code-art fallback changed');
assert.strictEqual(Object.keys(D.PLANTS).length,141);
assert.strictEqual(Object.keys(D.ZOMBIES).length,81);
console.log(`${looks} animated looks; ${count} drawn frames render unchanged; finite canvas reuse, action progress, head metadata and legacy fallbacks pass.`);
